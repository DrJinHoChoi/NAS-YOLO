#!/usr/bin/env python3
"""
Generate LaTeX Tables from Experiment Results
================================================
Reads evaluation JSONs and produces camera-ready LaTeX tables
for direct inclusion in the ECCV paper.

Usage:
    python -m nas_yolo.experiments.generate_tables --results-dir runs/eccv2026 --output tables/
"""

import os
import sys
import json
import argparse
from typing import Dict, List, Optional


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results-dir", type=str, required=True)
    parser.add_argument("--output", type=str, default="tables")
    return parser.parse_args()


def load_results(results_dir: str) -> Dict[str, Dict]:
    """Load all result JSONs from directory."""
    results = {}
    for fname in os.listdir(results_dir):
        if fname.endswith("_results.json"):
            name = fname.replace("_results.json", "")
            with open(os.path.join(results_dir, fname)) as f:
                results[name] = json.load(f)
    return results


def generate_main_table(results: Dict[str, Dict], output_path: str):
    """Generate Table 1: Main comparison table."""
    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("  \\centering")
    lines.append("  \\caption{\\textbf{Comparison with real-time detectors on COCO val2017.}}")
    lines.append("  \\label{tab:main_auto}")
    lines.append("  \\vspace{4pt}")
    lines.append("  \\small")
    lines.append("  \\setlength{\\tabcolsep}{4pt}")
    lines.append("  \\begin{tabular}{l|ccc|cc|cc}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Model} & \\textbf{Params} & \\textbf{FLOPs} & \\textbf{FPS} & "
                  "\\textbf{mAP} & \\textbf{mAP$_{50}$} & \\textbf{mAP-C} & \\textbf{BSI} \\\\")
    lines.append("    & (M) & (G) & & (\\%) & (\\%) & (\\%) & \\\\")
    lines.append("    \\midrule")

    # Known baselines (from papers, these are reference values)
    baselines = [
        ("YOLOv8-n", "3.2", "8.7", "350", "37.3", "52.6", "--", "--"),
        ("YOLOv8-s", "11.2", "28.6", "280", "44.9", "61.8", "--", "--"),
        ("YOLOv9-t", "2.0", "7.7", "340", "38.3", "53.1", "--", "--"),
        ("YOLOv9-s", "7.2", "26.7", "260", "46.8", "63.4", "--", "--"),
        ("YOLOv10-n", "2.3", "6.7", "390", "37.3", "52.3", "--", "--"),
        ("YOLOv10-s", "7.2", "21.6", "300", "46.3", "63.0", "--", "--"),
        ("YOLOv11-n", "2.6", "6.5", "370", "39.5", "56.1", "--", "--"),
        ("YOLOv11-s", "9.4", "21.5", "290", "47.0", "64.0", "--", "--"),
        ("YOLOv12-n", "2.6", "6.4", "355", "40.6", "57.2", "--", "--"),
        ("YOLOv12-s", "9.3", "21.4", "285", "48.0", "65.1", "--", "--"),
        ("RT-DETR-R18", "20.0", "60.0", "210", "46.5", "63.8", "--", "--"),
    ]

    for name, params, flops, fps, map_val, map50, mapc, bsi in baselines:
        lines.append(f"    {name} & {params} & {flops} & {fps} & {map_val} & {map50} & {mapc} & {bsi} \\\\")

    lines.append("    \\midrule")

    # Our results
    for model_name in ["nasyolo_n", "nasyolo_s_full"]:
        if model_name in results:
            r = results[model_name]
            info = r.get("model_info", {})
            clean = r.get("clean", {})
            corruption = r.get("corruption", {})
            stability = r.get("stability", {})
            latency = r.get("latency", {})

            display_name = "\\textbf{NAS-YOLO-n}" if "n" in model_name else "\\textbf{NAS-YOLO-s}"
            params_m = f"{info.get('total_params_M', 0):.1f}"
            flops_g = f"--"  # Fill from benchmark
            fps = f"{latency.get('throughput_fps', 0):.0f}" if latency.get('throughput_fps') else "--"
            map_val = f"{clean.get('mAP', 0)*100:.1f}" if clean.get('mAP') else "--"
            map50 = f"{clean.get('mAP50', 0)*100:.1f}" if clean.get('mAP50') else "--"
            mapc = f"{corruption.get('mAP_C', 0)*100:.1f}" if corruption.get('mAP_C') else "--"
            bsi = f"{stability.get('BSI', 0):.3f}" if stability.get('BSI') else "--"

            lines.append(f"    {display_name} & {params_m} & {flops_g} & {fps} & "
                         f"{map_val} & {map50} & {mapc} & {bsi} \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Generated: {output_path}")


def generate_ablation_table(results: Dict[str, Dict], output_path: str):
    """Generate Table: Ablation study."""
    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("  \\centering")
    lines.append("  \\caption{\\textbf{Ablation study} on COCO val2017 using NAS-YOLO-s.}")
    lines.append("  \\label{tab:ablation_auto}")
    lines.append("  \\vspace{4pt}")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{ccc|ccc|c}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{S3M} & \\textbf{Gate} & \\textbf{TCL} & "
                  "\\textbf{mAP} & \\textbf{mAP-C} & \\textbf{BSI} & \\textbf{Params} \\\\")
    lines.append("    \\midrule")

    ablation_configs = [
        ("ablation_no_temporal", "\\xmark", "\\xmark", "\\xmark"),
        ("ablation_no_gate", "\\cmark", "\\xmark", "\\xmark"),
        ("ablation_no_tcl", "\\cmark", "\\cmark", "\\xmark"),
        ("nasyolo_s_full", "\\cmark", "\\cmark", "\\cmark"),
    ]

    for model_key, s3m, gate, tcl in ablation_configs:
        if model_key in results:
            r = results[model_key]
            clean = r.get("clean", {})
            corruption = r.get("corruption", {})
            stability = r.get("stability", {})
            info = r.get("model_info", {})

            map_val = f"{clean.get('mAP', 0)*100:.1f}" if clean.get('mAP') else "--"
            mapc = f"{corruption.get('mAP_C', 0)*100:.1f}" if corruption.get('mAP_C') else "--"
            bsi = f"{stability.get('BSI', 0):.3f}" if stability.get('BSI') else "--"
            params = f"{info.get('total_params_M', 0):.1f}M" if info.get('total_params_M') else "--"

            lines.append(f"    {s3m} & {gate} & {tcl} & {map_val} & {mapc} & {bsi} & {params} \\\\")
        else:
            lines.append(f"    {s3m} & {gate} & {tcl} & -- & -- & -- & -- \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Generated: {output_path}")


def generate_corruption_table(results: Dict[str, Dict], output_path: str):
    """Generate Table: Per-corruption category breakdown."""
    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("  \\centering")
    lines.append("  \\caption{\\textbf{Per-corruption category mAP-C} on COCO-C.}")
    lines.append("  \\label{tab:corruption_auto}")
    lines.append("  \\vspace{4pt}")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{l|cccc|c}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Model} & \\textbf{Noise} & \\textbf{Blur} & "
                  "\\textbf{Weather} & \\textbf{Digital} & \\textbf{mAP-C} \\\\")
    lines.append("    \\midrule")

    for model_name in ["nasyolo_s_full", "ablation_no_temporal", "ablation_no_gate"]:
        if model_name in results:
            r = results[model_name]
            corruption = r.get("corruption", {})
            per_cat = corruption.get("per_category", {})

            display = model_name.replace("_", "\\_")
            noise = f"{per_cat.get('noise', 0)*100:.1f}" if per_cat.get('noise') else "--"
            blur = f"{per_cat.get('blur', 0)*100:.1f}" if per_cat.get('blur') else "--"
            weather = f"{per_cat.get('weather', 0)*100:.1f}" if per_cat.get('weather') else "--"
            digital = f"{per_cat.get('digital', 0)*100:.1f}" if per_cat.get('digital') else "--"
            mapc = f"{corruption.get('mAP_C', 0)*100:.1f}" if corruption.get('mAP_C') else "--"

            lines.append(f"    {display} & {noise} & {blur} & {weather} & {digital} & {mapc} \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Generated: {output_path}")


def generate_stability_table(results: Dict[str, Dict], output_path: str):
    """Generate Table: BSI breakdown."""
    lines = []
    lines.append("% Auto-generated by generate_tables.py")
    lines.append("\\begin{table}[t]")
    lines.append("  \\centering")
    lines.append("  \\caption{\\textbf{Box Stability Index (BSI) breakdown.}}")
    lines.append("  \\label{tab:bsi_auto}")
    lines.append("  \\vspace{4pt}")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{l|cccc}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Model} & \\textbf{BSI}$\\uparrow$ & "
                  "\\textbf{IoU} & \\textbf{Conf} & \\textbf{Center} \\\\")
    lines.append("    \\midrule")

    for model_name in sorted(results.keys()):
        r = results[model_name]
        stability = r.get("stability", {})
        if stability:
            display = model_name.replace("_", "\\_")
            bsi = f"{stability.get('BSI', 0):.3f}"
            iou = f"{stability.get('BoxIoU_stability', 0):.3f}"
            conf = f"{stability.get('Conf_stability', 0):.3f}"
            center = f"{stability.get('Center_stability', 0):.3f}"
            lines.append(f"    {display} & {bsi} & {iou} & {conf} & {center} \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"  Generated: {output_path}")


def main():
    args = parse_args()
    os.makedirs(args.output, exist_ok=True)

    print("Loading results...")
    results = load_results(args.results_dir)
    print(f"  Found {len(results)} result files: {list(results.keys())}")

    print("\nGenerating LaTeX tables...")
    generate_main_table(results, os.path.join(args.output, "table_main.tex"))
    generate_ablation_table(results, os.path.join(args.output, "table_ablation.tex"))
    generate_corruption_table(results, os.path.join(args.output, "table_corruption.tex"))
    generate_stability_table(results, os.path.join(args.output, "table_stability.tex"))

    print("\nDone! Copy .tex files into paper/tables/ for inclusion.")


if __name__ == "__main__":
    main()
